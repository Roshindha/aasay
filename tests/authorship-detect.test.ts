import { describe, expect, it } from "vitest";
import { detectCommitSignals, detectHistoryPatterns, detectReadmeStatements, detectStylePatterns, detectToolFiles } from "@/authorship/detect";
import type { CommitInfo } from "@/authorship/types";

const commit = (o: Partial<CommitInfo> & { sha: string }): CommitInfo => ({ message: "msg", authorName: "A Human", authorEmail: "a@example.com", date: "2026-01-01T10:00:00Z", ...o });
const f = (path: string, content: string) => ({ path, content });

describe("1. commit trailers and AI authors (strong)", () => {
  it("flags Co-Authored-By naming an AI tool, with the evidence line", () => {
    const [s] = detectCommitSignals([commit({ sha: "abcdef1234", message: "Add parser\n\nCo-Authored-By: Claude <noreply@anthropic.com>" })]);
    expect(s).toMatchObject({ kind: "commit-trailer", strength: "strong", ref: "commit-trailer:abcdef1", tool: "Claude" });
    expect(s!.evidence[0]).toContain("Co-Authored-By: Claude");
  });
  it("flags 'Generated with' lines and session-style trailers", () => {
    const out = detectCommitSignals([
      commit({ sha: "1111111aaa", message: "x\n\n🤖 Generated with [Claude Code](https://example.test)" }),
      commit({ sha: "2222222bbb", message: "y\n\nClaude-Session: abc123" }),
      commit({ sha: "3333333ccc", message: "z\n\nGenerated by ChatGPT" }),
    ]);
    expect(out.map((s) => s.ref)).toEqual(["commit-trailer:1111111", "commit-trailer:2222222", "commit-trailer:3333333"]);
  });
  it("flags AI-tool author identities but not dependency or CI bots, and not human co-authors", () => {
    const out = detectCommitSignals([
      commit({ sha: "aaaaaaa111", authorName: "copilot-swe-agent[bot]", authorEmail: "198982749+Copilot@users.noreply.github.com" }),
      commit({ sha: "bbbbbbb222", authorName: "dependabot[bot]", authorEmail: "49699333+dependabot[bot]@users.noreply.github.com" }),
      commit({ sha: "ccccccc333", authorName: "github-actions[bot]", authorEmail: "actions@github.com" }),
      commit({ sha: "ddddddd444", message: "pair\n\nCo-Authored-By: Jane Doe <jane@example.com>" }),
    ]);
    expect(out.map((s) => [s.kind, s.commit?.slice(0, 7)])).toEqual([["bot-author", "aaaaaaa"]]);
  });
});

describe("2. committed AI-tool files (strong)", () => {
  it.each([
    ["CLAUDE.md", "tool-file:CLAUDE.md"], ["docs/AGENTS.md", "tool-file:AGENTS.md"], [".cursorrules", "tool-file:.cursorrules"],
    [".cursor/rules/a.mdc", "tool-file:.cursor/"], [".claude/settings.json", "tool-file:.claude/"],
    [".github/copilot-instructions.md", "tool-file:.github/copilot-instructions.md"], [".windsurfrules", "tool-file:.windsurfrules"],
  ])("%s -> %s", (path, ref) => {
    const out = detectToolFiles(["src/a.ts", path]);
    expect(out).toHaveLength(1);
    expect(out[0]).toMatchObject({ ref, strength: "strong", file: path });
  });
  it("groups folder contents into one signal and ignores lookalikes", () => {
    const out = detectToolFiles([".claude/a", ".claude/b", ".claude/c", "notes/CLAUDE.md.txt", "src/claude.ts", "README.md"]);
    expect(out).toHaveLength(1);
    expect(out[0]!.evidence).toHaveLength(3);
  });
  it("explains what the file does not show", () => {
    expect(detectToolFiles(["CLAUDE.md"])[0]!.explanation).toMatch(/does not show how much code/);
  });
});

describe("3. README statements (moderate)", () => {
  it("detects AI-use statements and human-only claims", () => {
    const ai = detectReadmeStatements([f("README.md", "# P\n\nThis project was built with Claude Code and reviewed by me.\n")]);
    expect(ai[0]).toMatchObject({ ref: "readme:ai", claim: "ai-assisted", strength: "moderate", file: "README.md", line: 3 });
    const human = detectReadmeStatements([f("README.md", "100% hand-written, no AI involved.")]);
    expect(human[0]).toMatchObject({ ref: "readme:human", claim: "human-only" });
  });
  it.each(["AI-assisted development", "vibe coded over a weekend", "Pair programmed with ChatGPT.", "Written with the help of an AI assistant"])("reads %j as an AI claim", (line) => {
    expect(detectReadmeStatements([f("README.md", line)])[0]?.ref).toBe("readme:ai");
  });
  it("does not read negated phrases as AI claims", () => {
    const out = detectReadmeStatements([f("README.md", "This was not built with AI.")]);
    expect(out.map((s) => s.ref)).toEqual(["readme:human"]);
  });
  it("ignores code blocks, inline code and comments (documentation about the phrases)", () => {
    const md = "Detects phrases like `built with AI`.\n\n```\nbuilt with Claude\nhand-written\n```\n<!-- vibe coded -->\n";
    expect(detectReadmeStatements([f("README.md", md)])).toEqual([]);
  });
  it.each(["Assay reviews AI-written code in four lanes.", "Detects AI-generated text and AI-assisted commits.", "It finds hallucinations in code from AI assistants.", "Checks for AI-generated code."])("does not read a description of what a tool reviews as a disclosure: %s", (line) => {
    expect(detectReadmeStatements([f("README.md", line)])).toEqual([]);
  });
  it.each(["This repo is AI-assisted.", "AI-assisted development.", "The code was AI-generated and then edited by me."])("still reads real statements: %s", (line) => {
    expect(detectReadmeStatements([f("README.md", line)])[0]?.ref).toBe("readme:ai");
  });
  it.each([
    "The README claims no AI use, but strong signals exist.",
    "Flags hand-written claims that contradict the commits.",
    "There is no mode that helps a repository pass as human-written.",
    "Add a human-written fixture that shows how it misfires.",
    "e.g. a README that says 100% human-written",
    "Nine fixtures, including hand-written examples.",
    "No AI-tool trailers were found in the commit messages.",
  ])("does not read documentation about these claims as the project's own claim: %s", (line) => {
    expect(detectReadmeStatements([f("README.md", line)])).toEqual([]);
  });
  it.each(["This project is hand-written.", "I wrote all of it by hand: 100% human-written code.", "Pair programmed with Claude Code.", "No AI was used.", "Zero AI involvement."])("still reads genuine first-person claims: %s", (line) => {
    expect(detectReadmeStatements([f("README.md", line)]).length).toBe(1);
  });
  it("reads docs/ pages but not arbitrary markdown", () => {
    expect(detectReadmeStatements([f("docs/about.md", "AI-assisted")]).length).toBe(1);
    expect(detectReadmeStatements([f("notes/todo.md", "AI-assisted")]).length).toBe(0);
  });
});

describe("4. commit-history patterns (moderate at most)", () => {
  const at = (min: number) => new Date(Date.UTC(2026, 0, 1, 10, min)).toISOString();
  it("burst of large commits is moderate and carries the history caveat", () => {
    const cs = Array.from({ length: 6 }, (_, i) => commit({ sha: `b${i}00000`, date: at(i * 4), additions: 400, deletions: 10 }));
    const [s] = detectHistoryPatterns(cs);
    expect(s).toMatchObject({ ref: "history:burst", strength: "moderate" });
    expect(s!.caveat).toMatch(/innocent explanations/);
  });
  it("does not flag the same large commits spread over days", () => {
    const cs = Array.from({ length: 6 }, (_, i) => commit({ sha: `c${i}00000`, date: new Date(Date.UTC(2026, 0, 1 + i)).toISOString(), additions: 400 }));
    expect(detectHistoryPatterns(cs)).toEqual([]);
  });
  it("one very large initial commit is speculative", () => {
    const cs = [commit({ sha: "root000", date: at(0), additions: 5000 }), commit({ sha: "next000", date: "2026-01-05T10:00:00Z", additions: 20 })];
    expect(detectHistoryPatterns(cs)).toMatchObject([{ ref: "history:large-initial", strength: "speculative" }]);
  });
  it("uniform structured messages are speculative; plain messages are not flagged", () => {
    const body = "\n\n- one\n- two";
    const uniform = Array.from({ length: 10 }, (_, i) => commit({ sha: `u${i}00000`, message: `feat(x): thing ${i}${body}`, date: new Date(Date.UTC(2026, 0, 1 + i)).toISOString() }));
    expect(detectHistoryPatterns(uniform)).toMatchObject([{ ref: "history:uniform-messages", strength: "speculative" }]);
    const plain = Array.from({ length: 10 }, (_, i) => commit({ sha: `p${i}00000`, message: `fix thing ${i}`, date: new Date(Date.UTC(2026, 0, 1 + i)).toISOString() }));
    expect(detectHistoryPatterns(plain)).toEqual([]);
  });
  it("needs at least two commits", () => { expect(detectHistoryPatterns([commit({ sha: "only000", additions: 9000 })])).toEqual([]); });
});

describe("5. code-style patterns (always speculative, always with the caveat)", () => {
  const many = (line: string, n: number) => Array.from({ length: n }, () => line).join("\n");
  it("placeholders", () => {
    const out = detectStylePatterns([f("a.py", many("    pass  # TODO", 3))]);
    expect(out).toMatchObject([{ ref: "style:placeholder", strength: "speculative" }]);
    expect(out[0]!.caveat).toMatch(/weak evidence/);
  });
  it("comment density needs two dense files", () => {
    const dense = (n: string) => f(n, Array.from({ length: 60 }, (_, i) => (i % 2 ? "x = 1" : "# note")).join("\n"));
    expect(detectStylePatterns([dense("a.py")])).toEqual([]);
    expect(detectStylePatterns([dense("a.py"), dense("b.py")]).map((s) => s.ref)).toEqual(["style:comment-density"]);
  });
  it("generic names", () => {
    const src = ["def process_data(x):", "def handle_data(x):", "def foo():", "def bar():"].join("\n");
    expect(detectStylePatterns([f("a.py", src)]).map((s) => s.ref)).toEqual(["style:generic-names"]);
  });
  it("templated docstrings", () => {
    const fn = (i: number) => `def f${i}(a):\n    """Do it.\n\n    Args:\n        a: x\n    Returns:\n        y\n    """\n    return a\n`;
    const out = detectStylePatterns([f("a.py", Array.from({ length: 9 }, (_, i) => fn(i)).join("\n"))]);
    expect(out.map((s) => s.ref)).toEqual(["style:boilerplate-docs"]);
  });
  it("does not flag capitalised component names, and ignores test, fixture and e2e code", () => {
    expect(detectStylePatterns([f("src/ui.tsx", ["function Bar() {}", "const Foo = 1;", "function Baz() {}", "const Bar2 = 2; function Foo() {}"].join("\n"))])).toEqual([]);
    const todo = many("    pass  # TODO", 5);
    expect(detectStylePatterns([f("tests/a.py", todo), f("e2e/b.ts", todo), f("src/a.test.ts", todo), f("fixtures/x.py", todo), f("test_a.py", todo)])).toEqual([]);
  });
  it("never reports strong or moderate strength, and ignores ordinary code", () => {
    expect(detectStylePatterns([f("a.ts", "export function add(a: number, b: number) { return a + b; }")])).toEqual([]);
    const all = detectStylePatterns([f("a.py", many("pass  # TODO", 5))]);
    expect(all.every((s) => s.strength === "speculative")).toBe(true);
  });
});
